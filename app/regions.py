def validate_region(city: str | None, district: str | None) -> str | None:
    """返回错误信息；合法或留空时返回 None。"""
    c = (city or "").strip()
    d = (district or "").strip()
    if c and c not in CITY_DISTRICTS:
        return "城市请从下拉列表中选择"
    if d:
        if not c:
            return "请先选择城市，再选择区县"
        if d not in CITY_DISTRICTS[c]:
            return f"{c} 下没有「{d}」，区县请从下拉列表中选择"
    return None
