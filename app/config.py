"""应用配置：全部来自环境变量（pydantic-settings），不落盘敏感值。

一条例外：`APP_SECRET_KEY` 未配置（仍是占位默认值）时，**首次启动自动生成**随机密钥
并写入 `<CONFIG_DIR>/.app_secret`（0600），保证「开箱即用」的同时不再存在全网通用的固定密钥。
"""
from __future__ import annotations

import logging
import os
import secrets
from functools import lru_cache
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

log = logging.getLogger("crm.config")

DEFAULT_SECRET_KEY = "dev-insecure-change-me"
DEFAULT_ADMIN_PASS = "admin888"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", extra="ignore")

    app_name: str = "暖通空调客户管理系统"
    app_name_en: str = "HVAccRM"
    app_secret_key: str = DEFAULT_SECRET_KEY

    # 路径：配置 / 数据 / 缓存 / 日志分离（NAS 卷挂载）
    db_path: str = "/data/crm.db"
    data_dir: str = "/data"
    config_dir: str = "/config"

    admin_user: str = "admin"
    admin_pass: str = DEFAULT_ADMIN_PASS
    admin_force_password_change: bool = False
    # admin 初始密码仍是占位默认值（admin888）时，首启随机生成并写入 DATA_DIR/first_boot.txt
    admin_random_initial_password: bool = True

    tz: str = "Asia/Shanghai"
    log_level: str = "INFO"

    session_cookie: str = "crm_session"
    session_max_age: int = 12 * 3600

    # Cookie 的 Secure 标志：auto（请求判定为 https 才加）/ 1（强制加）/ 0（强制不加）
    # 反代终止 TLS 时靠 X-Forwarded-Proto 判定；判定不出来就用 auto 的保守行为（不加）。
    cookie_secure: str = "auto"
    # >0 时下发 HSTS（max-age 秒）。默认关闭——HSTS 更适合在反代层统一加。
    hsts_max_age: int = 0

    # 生产默认关闭 /api/docs、/api/openapi.json、/redoc（避免公网被拉到完整接口清单）
    api_docs: bool = False

    # 对外可访问的站点根地址（如 https://crm.example.com:8443）。
    # 空 = 用请求自身推断；反代终止 TLS 后推断可能得到 http，建议在反代场景显式设置。
    public_base_url: str = ""

    thumb_max_edge: int = 480
    thumb_quality: int = 80

    backup_keep: int = 30
    login_max_attempts: int = 5
    # 账号维度锁定阈值（与 IP 无关）——防止伪造 X-Forwarded-For 绕过登录锁定；
    # 阈值取得比 IP 维度高，避免别人连错几次就把你的账号锁死。
    login_max_attempts_account: int = 20
    login_lock_seconds: int = 300
    write_retry_attempts: int = 3

    # 进程内标记：本次启动是否自动生成了 APP_SECRET_KEY（后台页面据此提示）
    secret_autogenerated: bool = False

    @property
    def database_url(self) -> str:
        return f"sqlite:///{self.db_path}"

    @property
    def data_path(self) -> Path:
        return Path(self.data_dir)

    @property
    def media_dir(self) -> Path:
        return self.data_path / "media"

    @property
    def backup_dir(self) -> Path:
        return self.data_path / "backups"

    @property
    def log_dir(self) -> Path:
        return self.data_path / "logs"

    @property
    def is_secret_default(self) -> bool:
        return self.app_secret_key in {DEFAULT_SECRET_KEY, "change-me-please", ""}

    @property
    def is_admin_pass_default(self) -> bool:
        return self.admin_pass in {DEFAULT_ADMIN_PASS, "", "admin123"}

    def cookie_secure_flag(self, is_https: bool) -> bool:
        """三态开关：auto / 1 / 0。"""
        mode = str(self.cookie_secure or "auto").strip().lower()
        if mode in {"1", "true", "yes", "on"}:
            return True
        if mode in {"0", "false", "no", "off"}:
            return False
        return bool(is_https)

    def ensure_dirs(self) -> None:
        for p in (self.data_path, self.media_dir, self.backup_dir, self.log_dir):
            p.mkdir(parents=True, exist_ok=True)
        try:
            Path(self.db_path).parent.mkdir(parents=True, exist_ok=True)
        except OSError:
            pass


def _load_or_create_secret(config_dir: str) -> str:
    """读取 `<CONFIG_DIR>/.app_secret`；没有就生成一个（0600）并返回。

    落盘失败（如 `config` 以 :ro 挂载）时不阻断启动：退化为进程内随机密钥，
    代价是每次重启都会让已有会话失效（比"全网同一个固定密钥"安全得多）。
    """
    path = Path(config_dir) / ".app_secret"
    try:
        if path.is_file():
            existing = path.read_text(encoding="utf-8").strip()
            if existing:
                return existing
        path.parent.mkdir(parents=True, exist_ok=True)
        generated = secrets.token_urlsafe(48)
        fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(generated + "\n")
        os.chmod(path, 0o600)  # 个别挂载不认 create 时的 mode，显式再收一次
        log.warning("APP_SECRET_KEY 未配置，已自动生成随机密钥并保存到 %s（0600）", path)
        return generated
    except OSError as exc:
        log.warning("APP_SECRET_KEY 未配置且无法写入 %s（%s），本次使用进程内随机密钥", path, exc)
        return secrets.token_urlsafe(48)


@lru_cache
def get_settings() -> Settings:
    s = Settings()
    if s.is_secret_default:
        s.app_secret_key = _load_or_create_secret(s.config_dir)
        s.secret_autogenerated = True
    return s


def set_timezone(tz: str) -> None:
    try:
        os.environ["TZ"] = tz
        import time

        time.tzset()
    except Exception:  # pragma: no cover - 仅影响日志显示时间
        pass
