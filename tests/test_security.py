# ------------------------------------------------------------------ 登录锁定
@pytest.fixture
def locked_env(monkeypatch):
    from app import auth

    auth._attempts.clear()
    monkeypatch.setattr(
        auth,
        "get_settings",
        lambda: SimpleNamespace(login_lock_seconds=300, login_max_attempts=5, login_max_attempts_account=20),
    )
    yield auth
    auth._attempts.clear()


def test_lockout_per_ip(locked_env):
    for _ in range(5):
        locked_env._record_failure("1.2.3.4", "bob")
    assert locked_env._wait_seconds("1.2.3.4", "bob") > 0
    assert locked_env._wait_seconds("9.9.9.9", "bob") == 0  # 换 IP 不受影响（账号维度还没到阈值）


def test_lockout_account_dimension_beats_xff_spoofing(locked_env):
    """每次换一个伪造 IP，仍应在账号维度被锁——这是防 XFF 绕过的核心。"""
    for i in range(20):
        locked_env._record_failure(f"10.0.0.{i}", "bob")
    assert locked_env._wait_seconds("10.0.0.250", "bob") > 0


def test_lockout_cleared_on_success(locked_env):
    locked_env._record_failure("1.2.3.4", "bob")
    locked_env._clear_failures("1.2.3.4", "bob")
    assert locked_env._wait_seconds("1.2.3.4", "bob") == 0


# ------------------------------------------------------------------ 客户端 IP
def _fake_request(xff: str | None, host: str = "192.0.2.10"):
    headers = {"x-forwarded-for": xff} if xff else {}
    return SimpleNamespace(headers=headers, client=SimpleNamespace(host=host))


def test_client_ip_accepts_valid_xff():
    from app.auth import get_client_ip

    assert get_client_ip(_fake_request("203.0.113.7, 10.0.0.1")) == "203.0.113.7"


def test_client_ip_ignores_garbage_xff():
    from app.auth import get_client_ip

    assert get_client_ip(_fake_request("not-an-ip")) == "192.0.2.10"
    assert get_client_ip(_fake_request("'; DROP TABLE users; --")) == "192.0.2.10"
    assert get_client_ip(_fake_request(None)) == "192.0.2.10"


def test_client_ip_handles_missing_client():
    from app.auth import get_client_ip

    headers = {}
    assert get_client_ip(SimpleNamespace(headers=headers, client=None)) == "-"


# ------------------------------------------------------------------ 异常脱敏
def _fake_req(path: str):
    return SimpleNamespace(
        url=SimpleNamespace(path=path), method="GET", headers={}, cookies={}, state=SimpleNamespace(user=None)
    )


def test_unhandled_exception_does_not_leak_details_json():
    """500 的 JSON 里不能出现 sqlite 报错/表名/路径，只能有追踪号。"""
    import asyncio
    import json

    from app.main import unhandled_handler

    secret_msg = "sqlite3.OperationalError: no such table: customers /data/crm.db"
    resp = asyncio.run(unhandled_handler(_fake_req("/api/x"), RuntimeError(secret_msg)))
    body = json.loads(resp.body)
    assert "sqlite3" not in body["detail"]
    assert "no such table" not in body["detail"]
    assert "/data/crm.db" not in body["detail"]
    assert body["trace_id"]


def test_unhandled_exception_does_not_leak_details_html():
    import asyncio

    from app.main import unhandled_handler

    secret_msg = "OperationalError: no such column: secret_col"
    resp = asyncio.run(unhandled_handler(_fake_req("/customers"), RuntimeError(secret_msg)))
    text = resp.body.decode("utf-8")
    assert "no such column" not in text
    assert "追踪号" in text


def test_integrity_error_hides_original_sql():
    import asyncio

    from app.main import integrity_handler

    class _Orig:
        def __str__(self):
            return "UNIQUE constraint failed: users.username"

    class _Exc(Exception):
        orig = _Orig()

    resp = asyncio.run(integrity_handler(_fake_req("/admin/users"), _Exc()))
    text = resp.body.decode("utf-8")
    assert "UNIQUE constraint" not in text
    assert "users.username" not in text
    assert "数据冲突" in text

