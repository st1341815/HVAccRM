"""安全回归测试：覆盖「审计报告」里修掉的每一类问题，防止回退。

对应关系：
- 开放重定向（`//evil.com`）      → test_safe_next_*
- CSRF 双提交 token                → test_csrf_*
- 密钥/口令首启随机化              → test_secret_* / test_admin_*
- Cookie Secure 三态               → test_cookie_secure_flag_*
- 登录锁定（账号维度，防伪造 XFF）  → test_lockout_*
- 客户端 IP 取值（XFF 校验）        → test_client_ip_*
"""
from __future__ import annotations

import os
import stat
from pathlib import Path
from types import SimpleNamespace

import pytest

from app import security
from app.config import DEFAULT_SECRET_KEY, Settings, _load_or_create_secret
from app.utils import safe_next


# ------------------------------------------------------------------ 开放重定向
@pytest.mark.parametrize(
    "value",
    [
        "//evil.com",
        "///evil.com",
        "https://evil.com/x",
        "http://evil.com",
        "javascript:alert(1)",
        "evil.com",
        "",
        None,
        "/\\evil.com",
        "//evil.com/%2e%2e/x",
    ],
)
def test_safe_next_never_leaves_site(value):
    """核心性质：结果永远是站内绝对路径（不是协议相对、不含外部主机）。"""
    out = safe_next(value, "/")
    assert out.startswith("/")
    assert not out.startswith("//")
    assert "evil.com" not in out
    assert "://" not in out


@pytest.mark.parametrize("value", ["/", "/customers", "/customers?q=1", "/cases/share/abc#x"])
def test_safe_next_keeps_local(value):
    assert safe_next(value, "/") == value


def test_safe_next_strips_own_origin_to_path():
    """自己域名的绝对 URL 会被裁成站内路径（不算外跳）。"""
    assert safe_next("https://crm.example.com/customers?x=1") == "/customers?x=1"


# ------------------------------------------------------------------ CSRF
def test_csrf_roundtrip():
    token = security.make_csrf_token()
    assert security.verify_csrf(token, token) is True


def test_csrf_rejects_mismatch_and_garbage():
    a = security.make_csrf_token()
    b = security.make_csrf_token()
    assert security.verify_csrf(a, b) is False
    assert security.verify_csrf(a, "") is False
    assert security.verify_csrf(None, a) is False
    assert security.verify_csrf("nosig", "nosig") is False      # 无签名段
    assert security.verify_csrf(a, a + "x") is False            # 篡改


def test_csrf_rejects_forged_signature():
    """攻击者自己造 nonce（没有密钥就签不出合法签名）。"""
    nonce = "attacker-nonce"
    forged = f"{nonce}.{'0' * 64}"
    assert security.verify_csrf(forged, forged) is False


# ------------------------------------------------------------------ 密钥随机化
def test_secret_autogenerated_and_reused(tmp_path: Path):
    first = _load_or_create_secret(str(tmp_path))
    assert first and first != DEFAULT_SECRET_KEY and len(first) >= 32
    path = tmp_path / ".app_secret"
    assert path.is_file()
    assert stat.S_IMODE(os.stat(path).st_mode) == 0o600
    assert _load_or_create_secret(str(tmp_path)) == first  # 重启复用，会话不失效


